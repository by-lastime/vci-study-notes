/** VCI content adapter for the copied ICS reader. Only local VCI Markdown is read. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {Marked,Renderer} from 'marked';
import hljs from 'highlight.js';
import {mathExtensions,diagnostics} from './math.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sourcePath=path.join(root,'../content/第一阶段复习讲义.md');
const source=fs.readFileSync(sourcePath,'utf8');
const esc=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const digest=s=>crypto.createHash('sha256').update(s).digest('hex');
const chunks=source.split(/^# /m).slice(1);
if(chunks.length!==16)throw Error('Expected guide plus 15 chapters');
function render(md,id,headings=[]){
 const renderer=new Renderer();let number=0;
 renderer.heading=function(t){
  const title=t.text.replace(/\$([^$]+)\$/g,'$1').replace(/[*`]/g,'');
  const section=`${id}-s${number++}`;
  headings.push({id:section,text:title,level:t.depth});
  return `<h${t.depth} id="${section}">${this.parser.parseInline(t.tokens)}</h${t.depth}>\n`;
 };
 renderer.code=function(t){const language=(t.lang||'text').split(/\s/)[0];const value=hljs.getLanguage(language)?hljs.highlight(t.text,{language,ignoreIllegals:true}).value:esc(t.text);return `<pre class="code-block"><code class="hljs language-${esc(language)}">${value}</code></pre>`;};
 const baseLink=renderer.link;
 renderer.link=function(t){if(t.href.startsWith('补充问答.md'))return `<a href="#doc=supplements" data-doc-link="supplements" data-supplement-question="${esc(/\bQ\d+\b/i.exec(t.text)?.[0]?.toUpperCase()||'Q001')}" aria-haspopup="dialog" aria-controls="supplement-dialog">${this.parser.parseInline(t.tokens)}</a>`;return baseLink.call(this,t);};
 const marked=new Marked({gfm:true,breaks:false,renderer,extensions:mathExtensions({id})});
 return marked.parse(md);
}
const docs=chunks.map((chunk,i)=>{
 const [title,...lines]=chunk.split('\n');let md='# '+title+'\n'+lines.join('\n');
 const id=i?`d${i}`:'overview', headings=[];
 let html;
 if(i===14){
  const [intro,rest]=md.split('## 14.1 题目');
  const [questions,answers]=rest.split('## 14.2 参考答案');
  // Slice on start markers rather than line endings: question bodies may span paragraphs.
  const qmarks=[...questions.matchAll(/^\*\*(\d+)\. /gm)],amarks=[...answers.matchAll(/^\*\*(\d+)\.\*\* /gm)];
  if(qmarks.length!==16||amarks.length!==16)throw Error('Expected exactly 16 exercises and answers');
  html=render(intro,id,headings);
  qmarks.forEach((m,j)=>{
   const q=questions.slice(m.index,qmarks[j+1]?.index??questions.length).trim();
   const a=answers.slice(amarks[j].index+amarks[j][0].length,amarks[j+1]?.index??answers.length).trim();
   const topic=/^\*\*\d+\. (.*?)\*\*/.exec(q)?.[1]||'';
   const sid=`${id}-exercise-${j+1}`;
   html+=`<h2 id="${sid}">第 ${j+1} 题 · ${esc(topic.replace(/。$/,''))}</h2>`+render(q,`${id}-q${j+1}`)+`<details class="exercise-answer" data-exercise="${j+1}"><summary>查看答案与解析</summary><div class="answer-body">${render(a,`${id}-a${j+1}`)}</div></details>`;
   headings.push({id:sid,text:`第 ${j+1} 题 · ${topic}`,level:2});
  });
 }else html=render(md,id,headings);
 return {id,title,shortTitle:title.replace(/^\d+\s*/,''),nav:true,day:i||null,kind:i===13?'answers':i?'lesson':'guide',html,headings,sourcePath:path.relative(path.dirname(root),sourcePath).split(path.sep).join('/')};
});
const qaPath=path.join(root,'../content/补充问答.md'),qmd=fs.readFileSync(qaPath,'utf8'),qheadings=[];
docs.push({id:'supplements',title:'补充问答',shortTitle:'补充问答',kind:'supplement',day:null,nav:false,sourcePath:'content/补充问答.md',headings:qheadings,html:render(qmd,'supplements',qheadings)});
if(diagnostics.mathErrors.length)throw Error(JSON.stringify(diagnostics.mathErrors,null,2));
fs.cpSync(path.join(root,'../content/assets'),path.join(root,'assets'),{recursive:true});
fs.mkdirSync(path.join(root,'downloads'),{recursive:true});


const version=digest(JSON.stringify(docs)).slice(0,20),generatedAt=new Date().toISOString();
const payload={docs,version,generatedAt,sourceMap:{},publicRelease:true};
fs.writeFileSync(path.join(root,'content.js.tmp'),'/* Generated from content/*.md; do not edit this file. */\nwindow.VCI_CONTENT='+JSON.stringify(payload).replace(/</g,'\\u003c')+';\n');
fs.renameSync(path.join(root,'content.js.tmp'),path.join(root,'content.js'));
fs.writeFileSync(path.join(root,'build-version.json'),JSON.stringify({version,generatedAt,docs:docs.length,mathCount:diagnostics.mathCount}));
fs.writeFileSync(path.join(root,'build-diagnostics.json'),JSON.stringify({...diagnostics,chapters:16,exercises:16,sourceSha256:digest(source)},null,2));
console.log(`Built ${docs.length} documents, ${diagnostics.mathCount} formulas, 16 folded answers. No math errors.`);
